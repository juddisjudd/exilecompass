// Generates VOICE-COMMANDS.md (repo root) from the same data the app uses:
//   - src-tauri/resources/kws/keywords_raw.txt  spoken forms per phrase id
//   - src/lib/voicePhrases.ts                    groups + label keys
//   - messages/en.json                           labels and group names
//
//   bun run voice-docs                 # rewrite VOICE-COMMANDS.md
//   bun run voice-docs --wiki <dir>    # also write <dir>/Voice-Commands.md
//                                      # (a checkout of exilecompass.wiki.git)
//
// The GitHub wiki repo only exists after its first page is created in the web
// UI (Wiki tab → "Create the first page"); until then `--wiki` has nothing to
// clone into. Run this whenever keywords_raw.txt or the phrase labels change.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  VOICE_GROUP_ORDER, VOICE_GROUP_LABEL_KEYS, VOICE_PHRASE_LABEL_KEYS, voicePhraseGroup,
} from '../src/lib/voicePhrases.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const KEYWORDS = join(ROOT, 'src-tauri', 'resources', 'kws', 'keywords_raw.txt');
const MESSAGES = join(ROOT, 'messages', 'en.json');
const OUT = join(ROOT, 'VOICE-COMMANDS.md');

const args = process.argv.slice(2);
const wikiDir = args.includes('--wiki') ? args[args.indexOf('--wiki') + 1] : null;

const en = JSON.parse(readFileSync(MESSAGES, 'utf8'));

// id -> spoken forms, in file order (first one is the primary).
const spoken = new Map();
for (const line of readFileSync(KEYWORDS, 'utf8').split(/\r?\n/)) {
  const m = /^(.+?)\s+@([a-z0-9]+)\s*$/.exec(line.trim());
  if (!m) continue;
  const phrase = m[1].toLowerCase();
  if (!spoken.has(m[2])) spoken.set(m[2], []);
  spoken.get(m[2]).push(phrase);
}

const ids = [...spoken.keys()];
const missingLabel = ids.filter((id) => !VOICE_PHRASE_LABEL_KEYS[id] || !en[VOICE_PHRASE_LABEL_KEYS[id]]);
if (missingLabel.length) {
  console.error(`[voice-docs] no label for: ${missingLabel.join(', ')}`);
  process.exit(1);
}

const esc = (s) => s.replace(/\|/g, '\\|');
const lines = [];
lines.push('# Voice commands');
lines.push('');
lines.push(`Every command starts with **"compass"**. Say the whole phrase as one piece, without a pause after "compass". Recognition runs offline against a bundled keyword model; nothing is recorded or sent anywhere.`);
lines.push('');
lines.push('Turn voice commands on with the mic toggle in the footer, or in Settings → Voice Commands, where you can also pick the microphone. Commands that answer out loud use your system voice by default, or your own ElevenLabs key if you add one (Settings → Voice Replies).');
lines.push('');
lines.push(`${ids.length} commands, ${[...spoken.values()].flat().length} spoken forms.`);
lines.push('');

for (const group of VOICE_GROUP_ORDER) {
  const inGroup = ids.filter((id) => voicePhraseGroup(id) === group);
  if (!inGroup.length) continue;
  const title = group === 'other' ? 'Other' : en[VOICE_GROUP_LABEL_KEYS[group]];
  lines.push(`## ${title}`);
  lines.push('');
  lines.push('| Say | Does |');
  lines.push('|-----|------|');
  for (const id of inGroup) {
    const forms = spoken.get(id).map((f) => `**${esc(f)}**`).join(' or ');
    lines.push(`| ${forms} | ${esc(en[VOICE_PHRASE_LABEL_KEYS[id]])} |`);
  }
  lines.push('');
}

lines.push('## Tips');
lines.push('');
lines.push('- If a command is not picked up, say it again as one continuous phrase. A pause after "compass" is the most common cause of a miss.');
lines.push('- Settings → Voice Commands shows a live microphone level. If it stays flat while you talk, pick a different input device.');
lines.push('- Build commands read from the build imported on the Build tab (PoE2). Objective commands act on whichever guide is active: the PoE2 campaign guide or the PoE1 leveling guide.');
lines.push('- Timer commands act on the timer mode currently showing (Manual or Campaign).');
lines.push('');
lines.push('<!-- Generated by tools/build-voice-docs.mjs from keywords_raw.txt, voicePhrases.ts and messages/en.json. Do not edit by hand; run `bun run voice-docs`. -->');
lines.push('');

const md = lines.join('\n');
writeFileSync(OUT, md);
console.log(`[voice-docs] wrote ${OUT} (${ids.length} commands)`);

if (wikiDir) {
  if (!existsSync(wikiDir)) {
    console.error(`[voice-docs] --wiki dir not found: ${wikiDir}`);
    process.exit(1);
  }
  const wikiOut = join(wikiDir, 'Voice-Commands.md');
  writeFileSync(wikiOut, md);
  console.log(`[voice-docs] wrote ${wikiOut}`);
}
